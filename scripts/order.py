#!/usr/bin/env python3
"""On-disk ORDER and REPORT state machine: `<runs>/<prd>/order-<id>.md`.

  open       --prd 213 --id 213-C --owner "Dev Front" --scope "..." --authorization "<exact quote>" --repo <worktree>
             [--resumes 213-B]
  start      --prd 213 --id 213-C --owner "Dev Front"
  report     --prd 213 --id 213-C --owner "Dev Front" --status partial|completed|failed --evidence <file/snippet>
             --next "<step> · <owner>" [--effect commit:abc123 ...]
  check      <file>                   validate identity, status, and SHA-256 integrity; exit 1 if invalid
  reconcile  --prd 213                after reset: exit 0 = all final · 1 = open ORDER, resume with owner ·
                                      2 = halt dispatch (invalid file, unreported commit, unreadable repo)

Rules:
- Only opens an ORDER whose `--authorization` is a full quoted string in `<runs>/<prd>/authorization.md`
  on a line without `[closed]`.
- Re-opening the same ID with identical owner/scope returns the existing file (idempotent duplicate delivery);
  different owner/scope fails.
- REPORT is recorded before `maestri ask`; final status (`completed`, `failed`) is immutable (repeating the
  exact same REPORT is a no-op).
- External effects are never repeated: `--resumes` inherits effects from a closed ORDER and `reconcile` lists them.
- At the context ceiling, when Bash is blocked, the owner writes `<runs>/<prd>/report-<id>-ceiling.md` via Write
  (exempted) and `reconcile` surfaces it.
"""
import argparse
import contextlib
import fcntl
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time


def resolve_runs_dir() -> str:
    env_runs = os.environ.get("MAESTRI_RUNS")
    if env_runs:
        return env_runs
    cfg_candidates = [
        os.environ.get("MAESTRI_CONFIG", ""),
        os.path.join(os.getcwd(), "board.config.json"),
        os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "board.config.json"),
    ]
    for cfg_path in cfg_candidates:
        if cfg_path and os.path.isfile(cfg_path):
            try:
                with open(cfg_path, encoding="utf-8") as f:
                    data = json.load(f)
                runs_dir = (data.get("paths") or {}).get("runs_dir")
                if runs_dir:
                    return runs_dir
            except (OSError, ValueError):
                pass
    return "./planning/runs"


RUNS = resolve_runs_dir()
STATUSES = ("pending", "in_progress", "partial", "completed", "failed")
FINAL_STATUSES = ("completed", "failed")
REPORT_STATUSES = {"partial": "partial", "completed": "completed", "failed": "failed"}
EXTERNAL_EFFECTS = ("commit", "deploy", "migration", "workflow", "createdb", "push")
ID_RE = re.compile(r"^[0-9A-Za-z][0-9A-Za-z_-]*(\.[0-9A-Za-z_-]+)*$")
BLOCK = re.compile(r"```json\n(.*?)\n```", re.S)
QUOTE = re.compile(r'"([^"]+)"')
MIN_AUTH_LEN = 15


def now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%S%z")


def path_for(prd: str, oid: str) -> str:
    for val, name in ((prd, "prd"), (oid, "id")):
        if not ID_RE.match(val or "") or val.endswith(".tmp"):
            sys.exit(f"invalid {name}: {val!r}")
    return os.path.join(resolve_runs_dir(), prd, f"order-{oid}.md")


@contextlib.contextmanager
def locked(prd: str):
    """Single writer per PRD via flock on .order.lock so parallel REPORT calls never drop an effect."""
    d = os.path.join(resolve_runs_dir(), prd)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, ".order.lock"), "w", encoding="utf-8") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        yield


def seal(o: dict) -> str:
    body = {k: v for k, v in o.items() if k != "sha"}
    return hashlib.sha256(json.dumps(body, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


def load(path: str) -> tuple[dict, str]:
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = BLOCK.search(text)
    if not m:
        raise ValueError("missing json block")
    o = json.loads(m.group(1))
    if not isinstance(o, dict):
        raise ValueError("json block is not an object")
    return o, text


def save(path: str, o: dict, line: str) -> None:
    o["updated_at"] = now()
    o["sha"] = seal(o)
    hist = []
    if os.path.exists(path):
        _, old = load(path)
        hist = old.split("## History\n", 1)[1].splitlines() if "## History\n" in old else []
    hist.append(f"- {o['updated_at']} · {line}")
    text = (
        f"# ORDER {o['id']} · #{o['prd']}\n\n"
        "<!-- generated by scripts/order.py; manual edits invalidate sha -->\n\n"
        f"```json\n{json.dumps(o, indent=2, ensure_ascii=False)}\n```\n\n"
        "## History\n" + "\n".join(hist) + "\n"
    )
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".order-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def problems(path: str) -> list[str]:
    """List validation errors for an order file; empty list means valid. Never raises."""
    path = os.path.abspath(path)
    try:
        o, _ = load(path)
    except (OSError, ValueError) as e:
        return [f"unreadable: {e}"]
    out = []
    if os.path.basename(path) != f"order-{o.get('id')}.md":
        out.append(f"id {o.get('id')!r} does not match filename")
    if os.path.basename(os.path.dirname(path)) != str(o.get("prd")):
        out.append(f"prd {o.get('prd')!r} does not match directory")
    if o.get("status") not in STATUSES:
        out.append(f"invalid status: {o.get('status')!r}")
    effects = o.get("effects")
    if not isinstance(effects, list) or not all(
        isinstance(e, dict) and e.get("type") in EXTERNAL_EFFECTS and e.get("ref") for e in effects
    ):
        out.append("malformed effects")
    if o.get("sha") != seal(o):
        out.append("sha mismatch (edited manually)")
    for k in ("owner", "scope", "authorization", "repo", "base"):
        if not o.get(k):
            out.append(f"empty {k}")
    if o.get("status") in ("partial",) + FINAL_STATUSES:
        for k in ("evidence", "next"):
            if not o.get(k):
                out.append(f"{o['status']} missing {k}")
    return out


def authorized(prd: str, quote: str) -> bool:
    """Quote must match an entire quoted string on a line without [closed] in authorization.md."""
    if len(quote.strip()) < MIN_AUTH_LEN:
        return False
    auth_path = os.path.join(resolve_runs_dir(), prd, "authorization.md")
    try:
        with open(auth_path, encoding="utf-8") as f:
            return any(
                quote.strip() in QUOTE.findall(line)
                for line in f
                if "[closed]" not in line
            )
    except OSError:
        return False


def git(repo: str, *args: str) -> str:
    r = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, check=False)
    if r.returncode:
        raise RuntimeError(f"git {' '.join(args)} in {repo}: {r.stderr.strip()}")
    return r.stdout.strip()


def get_order(a) -> tuple[str, dict]:
    p = path_for(a.prd, a.id)
    if not os.path.exists(p):
        sys.exit(f"ORDER {a.id} does not exist at {p}")
    bad = problems(p)
    if bad:
        sys.exit(f"ORDER {a.id} is invalid: {'; '.join(bad)}")
    o, _ = load(p)
    if a.owner != o["owner"]:
        sys.exit(f"ORDER {a.id} belongs to {o['owner']!r}, not {a.owner!r}")
    return p, o


def cmd_open(a) -> int:
    p = path_for(a.prd, a.id)
    if os.path.exists(p):
        o, _ = load(p)
        if (o.get("owner"), o.get("scope")) == (a.owner, a.scope) and not problems(p):
            print(f"ORDER {a.id} already exists ({o['status']}): {p}")
            return 0
        sys.exit(
            f"ORDER {a.id} already exists with different owner/scope or is invalid: "
            f"use a new id (e.g. {a.id}.2) and --resumes"
        )
    if not authorized(a.prd, a.authorization):
        sys.exit(
            f"unauthorized: {a.authorization!r} is not a full quoted string (on a line without [closed]) "
            f"in {resolve_runs_dir()}/{a.prd}/authorization.md"
        )
    try:
        base = git(a.repo, "rev-parse", "HEAD")
    except RuntimeError as e:
        sys.exit(str(e))
    o = {
        "id": a.id,
        "prd": a.prd,
        "owner": a.owner,
        "scope": a.scope,
        "authorization": a.authorization,
        "status": "pending",
        "repo": os.path.abspath(a.repo),
        "base": base,
        "revision": None,
        "evidence": None,
        "effects": [],
        "next": None,
        "opened_at": now(),
        "resumes": None,
    }
    if a.resumes:
        po = path_for(a.prd, a.resumes)
        if not os.path.exists(po) or problems(po):
            sys.exit(f"--resumes {a.resumes}: ORDER missing or invalid")
        prev, _ = load(po)
        if prev["status"] not in FINAL_STATUSES:
            sys.exit(f"--resumes {a.resumes}: still {prev['status']}; close with REPORT first")
        o["resumes"] = a.resumes
        o["effects"] = [dict(e, inherited=True) for e in prev["effects"]]
    with locked(a.prd):
        if os.path.exists(p):
            sys.exit(f"ORDER {a.id} created concurrently; retry")
        save(p, o, f"opened by Manager → {a.owner}: {a.scope}")
    print(p)
    return 0


def cmd_start(a) -> int:
    with locked(a.prd):
        p, o = get_order(a)
        if o["status"] != "pending":
            print(f"ORDER {a.id} is already {o['status']}")
            return 0
        o["status"] = "in_progress"
        save(p, o, f"{a.owner} started")
    return 0


def parse_effects(raw: list[str]) -> list[dict]:
    out = []
    for e in raw:
        kind, _, ref = e.partition(":")
        kind = kind.strip().lower()
        if kind not in EXTERNAL_EFFECTS or not ref.strip():
            sys.exit(f"invalid effect: {e!r} (expected type:ref, type in {', '.join(EXTERNAL_EFFECTS)})")
        out.append({"type": kind, "ref": ref.strip()})
    return out


def cmd_report(a) -> int:
    status = REPORT_STATUSES.get(a.status)
    if not status:
        sys.exit(f"invalid REPORT status: expected partial|completed|failed, got {a.status!r}")
    effects = parse_effects(a.effect)
    update = {"status": status, "evidence": a.evidence, "next": a.next}
    with locked(a.prd):
        p, o = get_order(a)
        known = [{"type": e["type"], "ref": e["ref"]} for e in o["effects"]]
        if o["status"] in FINAL_STATUSES:
            if all(o[k] == v for k, v in update.items()) and all(e in known for e in effects):
                print(f"REPORT {a.id} already recorded ({o['status']}); no changes")
                return 0
            sys.exit(
                f"ORDER {a.id} is already {o['status']}: different REPORT requires a new ORDER (--resumes {a.id})"
            )
        o.update(update)
        o["effects"] += [e for e in effects if e not in known]
        try:
            o["revision"] = git(o["repo"], "rev-parse", "--short", "HEAD")
        except RuntimeError as e:
            print(f"warning: revision could not be read ({e})", file=sys.stderr)
        save(p, o, f"REPORT {status} · {a.evidence} · next: {a.next}")
    print(f"REPORT {a.id} · Status: {status} · Evidence: {a.evidence} · Next: {a.next}")
    return 0


def unreported_commits(o: dict) -> list[str]:
    """Commits after ORDER base that no REPORT has recorded."""
    recorded = [e["ref"] for e in o["effects"] if e["type"] == "commit"]
    shas = git(o["repo"], "rev-list", f"{o['base']}..HEAD").split()
    return [s for s in shas if not any(s.startswith(r) or r.startswith(s) for r in recorded)]


def reconcile_one(d: str, f: str) -> int:
    p = os.path.join(d, f)
    bad = problems(p)
    if bad:
        print(f"✗ {f}: {'; '.join(bad)} → do not dispatch anything for this PRD until fixed")
        return 2
    o, _ = load(p)
    ext = [f"{e['type']}:{e['ref']}" for e in o["effects"]]
    mark = "✓" if o["status"] in FINAL_STATUSES else "•"
    print(
        f"{mark} {o['id']} · {o['status']} · owner {o['owner']} · "
        f"revision {o['revision'] or '—'} · next: {o['next'] or '—'}"
    )
    if ext:
        print(f"    already done, do not repeat: {', '.join(ext)}")
    if o["status"] in FINAL_STATUSES:
        return 0
    ceiling = os.path.join(d, f"report-{o['id']}-ceiling.md")
    if os.path.exists(ceiling):
        print(f"    REPORT written at context ceiling: {ceiling} → read and record via `report` on behalf of owner")
    try:
        new_commits = unreported_commits(o)
    except RuntimeError as e:
        print(f"    unreadable repo ({e}) → do not dispatch until checked manually")
        return 2
    if new_commits:
        print(
            f"    {len(new_commits)} commit(s) after ORDER without REPORT (latest: {new_commits[0][:9]}): "
            "lost session after effect → check disk and record REPORT for owner; do not redispatch"
        )
        return 2
    if o["status"] == "pending":
        print("    pending: not started; resending the same id is safe (open returns existing)")
    else:
        print(f"    {o['status']} with no new repo effects: `maestri check \"{o['owner']}\"` before resending")
    return 1


def cmd_reconcile(a) -> int:
    d = os.path.join(resolve_runs_dir(), a.prd)
    files = (
        sorted(f for f in os.listdir(d) if f.startswith("order-") and f.endswith(".md"))
        if os.path.isdir(d)
        else []
    )
    if not files:
        print(f"#{a.prd}: no ORDER files on disk")
        return 0
    code = 0
    for f in files:
        code = max(code, reconcile_one(d, f))
    return code


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("open", "start", "report", "reconcile"):
        s = sub.add_parser(name)
        s.add_argument("--prd", required=True)
        if name != "reconcile":
            s.add_argument("--id", required=True)
            s.add_argument("--owner", required=True)
        if name == "open":
            s.add_argument("--scope", required=True)
            s.add_argument("--authorization", required=True)
            s.add_argument("--repo", required=True)
            s.add_argument("--resumes")
        if name == "report":
            s.add_argument("--status", required=True)
            s.add_argument("--evidence", required=True)
            s.add_argument("--next", required=True)
            s.add_argument("--effect", action="append", default=[])
    c = sub.add_parser("check")
    c.add_argument("file")
    a = p.parse_args()
    if a.cmd == "check":
        bad = problems(a.file)
        print("OK" if not bad else "\n".join(bad))
        return 1 if bad else 0
    if a.cmd != "reconcile":
        path_for(a.prd, a.id)
    return {"open": cmd_open, "start": cmd_start, "report": cmd_report, "reconcile": cmd_reconcile}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
